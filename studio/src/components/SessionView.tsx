import { useContext, useMemo, useState } from "react";
import type { Session, SessionItem, SessionStatus } from "../api";
import { api } from "../api";
import { RootContext } from "../context";
import { designHref, problemHref } from "../route";
import {
  FOCUS_INFO,
  STATUS_LABEL,
  actionsFor,
  createdAttempt,
  isDesignItem,
  latestConsoleHref,
  runCommand,
  scoreBand,
} from "../sessions";
import { NavList } from "./panes";
import { PlanWithClaude, Stat, sessionNavGroups, useSessions } from "./PracticeBench";
import { Ring } from "./Ring";
import { Workbench } from "./Workbench";

const STATE_LABEL: Record<SessionItem["state"], string> = {
  todo: "to do",
  started: "started",
  attempted: "attempted",
  solved: "solved",
};

type SessionTab = "items" | "materials" | "results";

/** One session on the Workbench: Items / Materials / Results tabs, status actions in the footer. */
export function SessionView({ initial }: { initial: Session }) {
  const [s, setS] = useState(initial);
  const [error, setError] = useState<string | null>(null);
  const [tab, setTab] = useState<SessionTab>("items");
  const list = useSessions(undefined, s);
  const nav = useMemo(() => sessionNavGroups(list ?? [s], s.id), [list, s]);
  const act = (p: Promise<Session>) =>
    p.then(
      (next) => {
        setS(next);
        setError(null);
      },
      (e: unknown) => setError(String(e)),
    );
  const setStatus = (to: SessionStatus) => act(api.setStatus(s.id, to));
  const solved = s.items.filter((i) => i.state === "solved").length;
  const attempted = s.items.filter((i) => i.state !== "todo").length;
  const ordered = list ?? [s];
  const at = ordered.findIndex((x) => x.id === s.id);

  const header = (
    <div className={`rd-header pb-head pb-session-head ${s.status}`}>
      <div className="pb-ring">
        <Ring
          solved={s.score ?? 0}
          total={100}
          size={64}
          label={s.score === null ? "–" : `${s.score}`}
        />
      </div>
      <div className="rd-head-main">
        <div className="rd-kicker">
          <span className={`status-badge ${s.status}`}>{STATUS_LABEL[s.status]}</span>
          <span className="small">
            {FOCUS_INFO[s.target.focus].icon} {FOCUS_INFO[s.target.focus].label}
          </span>
          <span className="muted small">
            {s.generator === "claude" ? "🤖 planned by Claude" : "⚙️ generated by kb"} ·{" "}
            {s.created.slice(0, 10)}
          </span>
        </div>
        <h1>{s.title}</h1>
        <div className="pb-stats">
          {s.target.goal && <span className="pb-stat">🎯 {s.target.goal}</span>}
          <Stat n={`${Math.round(s.completion * 100)}%`} label="attempted" tone="accent" />
          <Stat n={`${solved}/${s.items.length}`} label="solved" tone="ok" />
          <Stat n={`${s.overall}`} label="overall /100" />
          {s.scope.minutes ? <span className="pb-stat">⏱ {s.scope.minutes} min</span> : null}
        </div>
      </div>
    </div>
  );

  const tabBtn = (t: SessionTab, icon: string, label: string, badge: number, done = false) => (
    <button
      key={t}
      className={`wb-tab pb-tab-${t} ${tab === t ? "on" : ""} ${done ? "done" : ""}`}
      onClick={() => setTab(t)}
      aria-pressed={tab === t}
    >
      {icon} {label}
      <span className="wb-tab-badge">{badge}</span>
    </button>
  );
  const tabs = (
    <>
      {tabBtn("items", "🧪", "Items", s.items.length, solved === s.items.length && solved > 0)}
      {tabBtn("materials", "📖", "Materials", s.materials.length)}
      {tabBtn("results", "🏁", "Results", attempted)}
    </>
  );

  const right = (
    <div className="pb-side">
      <section className="rd-card pb-score-card">
        <h4>Session score</h4>
        <div className="pb-score-ring">
          <Ring
            solved={s.score ?? 0}
            total={100}
            size={96}
            label={s.score === null ? "–" : `${s.score}`}
          />
        </div>
        <div className="progress-bar" title={`${Math.round(s.completion * 100)}% attempted`}>
          <span style={{ width: `${s.completion * 100}%` }} />
        </div>
        <div className="muted small">
          {attempted}/{s.items.length} attempted · {solved} solved
        </div>
      </section>
      {s.materials.length > 0 && (
        <section className="rd-card">
          <h4>📖 Learn first</h4>
          <ul className="pb-recent">
            {s.materials.map((m) => (
              <li key={`${m.subject}/${m.topic}`}>
                <a href={materialHref(m)}>{m.name}</a>
                <span className="muted small">{m.has_lesson ? "lesson" : "topic"}</span>
              </li>
            ))}
          </ul>
        </section>
      )}
      <PlanWithClaude />
    </div>
  );

  const footer = (
    <div className="pb-footer">
      <span className={`status-badge ${s.status}`}>{STATUS_LABEL[s.status]}</span>
      {actionsFor(s.status).map((a) => (
        <button
          key={a.to}
          className={`rd-btn ${a.to === "abandoned" ? "" : "primary"} pb-action`}
          onClick={() => setStatus(a.to)}
        >
          {a.label}
        </button>
      ))}
      {error && <span className="inline-error">⚠ {error}</span>}
      <span className="grow" />
      {at >= 0 && ordered.length > 1 && (
        <span className="muted">
          session {at + 1} / {ordered.length}
        </span>
      )}
      <a href="#/sessions">all sessions →</a>
    </div>
  );

  let center;
  if (tab === "items") {
    center = (
      <>
        {s.rationale.length > 0 && (
          <ul className="rationale">
            {s.rationale.map((r) => (
              <li key={r}>{r}</li>
            ))}
          </ul>
        )}
        <section>
          <h2 className="group-title">🧪 Problem set</h2>
          <div className="items">
            {s.items.map((it, i) => (
              <ItemRow
                key={it.id}
                item={it}
                index={i}
                onStart={(lang) => act(api.startAttempt(s.id, it.id, lang))}
                onStartDesign={() => {
                  const before = it.attempts;
                  api.startAttempt(s.id, it.id, "design").then(
                    (next) => {
                      setS(next);
                      const after = next.items.find((x) => x.id === it.id)?.attempts ?? [];
                      const created = createdAttempt(before, after);
                      if (created) window.location.hash = designHref(it.subject, it.slug, created);
                    },
                    (e: unknown) => setError(String(e)),
                  );
                }}
              />
            ))}
          </div>
        </section>
      </>
    );
  } else if (tab === "materials") {
    center =
      s.materials.length === 0 ? (
        <div className="pb-empty">
          <div className="pb-empty-icon">📖</div>
          <p>This session has no lessons to read first. Straight to the problems.</p>
        </div>
      ) : (
        <section>
          <h2 className="group-title">📖 Learn first</h2>
          <div className="materials">
            {s.materials.map((m) => (
              <a key={`${m.subject}/${m.topic}`} className="material" href={materialHref(m)}>
                <b>{m.name}</b>
                <span className="muted small">
                  {m.why ?? (m.has_lesson ? "lesson + quiz" : "topic page")}
                </span>
              </a>
            ))}
          </div>
        </section>
      );
  } else {
    center = (
      <section className="pb-results">
        <h2 className="group-title">🏁 Results</h2>
        <div className="pb-table-wrap">
          <table className="problems-table pb-table">
            <thead>
              <tr>
                <th>#</th>
                <th>Problem</th>
                <th>State</th>
                <th>Last run</th>
                <th>Score</th>
              </tr>
            </thead>
            <tbody>
              {s.items.map((it, i) => (
                <tr key={it.id} style={{ ["--i" as string]: i }}>
                  <td className="muted">{i + 1}</td>
                  <td>
                    <a href={problemHref(it.subject, it.slug)}>{it.title ?? it.slug}</a>
                  </td>
                  <td>
                    <span className={`state ${it.state}`}>{STATE_LABEL[it.state]}</span>
                  </td>
                  <td className="muted small">
                    {it.last_run
                      ? `${it.last_run.passed}/${it.last_run.total} · ${it.last_run.ts.slice(0, 16).replace("T", " ")}`
                      : "—"}
                  </td>
                  <td>
                    <span className={`score-chip ${scoreBand(it.score)}`}>
                      {it.score === null ? "–" : `${it.score}/100`}
                    </span>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        {s.history.length > 0 && (
          <>
            <h3>History</h3>
            <ol className="pb-history">
              {s.history.map((h) => (
                <li key={`${h.ts}-${h.status}`}>
                  <span className={`status-dot ${h.status}`} /> {STATUS_LABEL[h.status]}
                  <span className="muted small"> {h.ts.slice(0, 16).replace("T", " ")}</span>
                </li>
              ))}
            </ol>
          </>
        )}
        <p className="muted small">
          Scores come from your <code>kb run</code> results: 70 for passing cases, 20 for hitting
          the target complexity, 10 for passing on your first real try (running the empty stub
          doesn't count). Re-run an attempt and the score updates. Need a review? In Claude Code:{" "}
          <code>/review</code>.
        </p>
      </section>
    );
  }

  return (
    <Workbench
      id="sessions"
      header={header}
      tabs={tabs}
      left={{
        title: "Sessions",
        icon: "🎯",
        content: list ? (
          <NavList groups={nav} placeholder="Filter sessions…" />
        ) : (
          <div className="loader small-loader" aria-label="loading" />
        ),
      }}
      right={{ title: "Score", icon: "🏁", content: right }}
      footer={footer}
    >
      <div className="pb-center session pb-session">{center}</div>
    </Workbench>
  );
}

const materialHref = (m: Session["materials"][number]) =>
  m.has_lesson ? `#/learn/${m.subject}/${m.topic}` : `#/topic/${m.subject}/${m.topic}`;

function ItemRow({
  item,
  index,
  onStart,
  onStartDesign,
}: {
  item: SessionItem;
  index: number;
  onStart: (lang: "python" | "go") => void;
  onStartDesign: () => void;
}) {
  const design = isDesignItem(item);
  const consoleHref = latestConsoleHref(item);
  const root = useContext(RootContext);
  const [copied, setCopied] = useState<string | null>(null);
  const copy = (text: string) => {
    void navigator.clipboard.writeText(text);
    setCopied(text);
    setTimeout(() => setCopied(null), 1200);
  };
  const latest = item.attempt_paths[item.attempt_paths.length - 1];
  return (
    <div className={`item ${item.state}`} style={{ ["--i" as string]: index }}>
      <div className="item-num">{index + 1}</div>
      <div className="item-main">
        <div className="item-title">
          <a href={problemHref(item.subject, item.slug)}>{item.title ?? item.slug}</a>
          {item.difficulty && <span className={`badge ${item.difficulty}`}>{item.difficulty}</span>}
          <span className={`state ${item.state}`}>{STATE_LABEL[item.state]}</span>
        </div>
        {item.why && <div className="muted small">💡 {item.why}</div>}
        <div className="item-actions">
          {item.attempt_paths.map((p, k) => (
            <a key={p} className="attempt" href={`vscode://file${p}`} title="open in VS Code">
              ⧉ {item.attempts[k]}
            </a>
          ))}
          {latest && (
            <code
              className="cmd"
              onClick={() => copy(runCommand(latest, root))}
              title="click to copy"
            >
              {copied === runCommand(latest, root) ? "copied ✓" : runCommand(latest, root)}
            </code>
          )}
          {design ? (
            <>
              {consoleHref && (
                <a className="button-link primary" href={consoleHref}>
                  ▶ Open console
                </a>
              )}
              <button onClick={onStartDesign}>＋ New design attempt</button>
            </>
          ) : (
            <>
              <button onClick={() => onStart("python")}>＋ Python attempt</button>
              <button onClick={() => onStart("go")}>＋ Go attempt</button>
            </>
          )}
        </div>
      </div>
      <div className={`item-score ${scoreBand(item.score)}`}>
        {item.score === null ? "–" : item.score}
        <span>/100</span>
      </div>
    </div>
  );
}
