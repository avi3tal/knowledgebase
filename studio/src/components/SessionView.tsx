import { useContext, useState } from "react";
import type { Session, SessionItem, SessionStatus } from "../api";
import { api } from "../api";
import { RootContext } from "../context";
import { FOCUS_INFO, STATUS_LABEL, actionsFor, runCommand, scoreBand } from "../sessions";
import { Ring } from "./Ring";

const STATE_LABEL: Record<SessionItem["state"], string> = {
  todo: "to do",
  started: "started",
  attempted: "attempted",
  solved: "solved",
};

/** One session: target, materials, the problem set with per-item and session scores. */
export function SessionView({ initial }: { initial: Session }) {
  const [s, setS] = useState(initial);
  const [error, setError] = useState<string | null>(null);
  const act = (p: Promise<Session>) =>
    p.then(
      (next) => {
        setS(next);
        setError(null);
      },
      (e: unknown) => setError(String(e)),
    );
  const setStatus = (to: SessionStatus) => act(api.setStatus(s.id, to));
  const solved = s.items.filter((i) => i.state === "solved").length;

  return (
    <div className="session">
      <section className={`hero session-hero ${s.status}`}>
        <div className="hero-ring">
          <Ring
            solved={s.score ?? 0}
            total={100}
            size={84}
            label={s.score === null ? "–" : `${s.score}`}
          />
        </div>
        <div className="grow">
          <div className="hero-kicker">
            <span className={`status-badge ${s.status}`}>{STATUS_LABEL[s.status]}</span>
            {FOCUS_INFO[s.target.focus].icon} {FOCUS_INFO[s.target.focus].label} ·{" "}
            {s.generator === "claude" ? "🤖 planned by Claude" : "⚙️ generated by kb"}
          </div>
          <h1>{s.title}</h1>
          <div className="stats">
            {s.target.goal && <span className="stat">🎯 {s.target.goal}</span>}
            <span className="stat">
              <b>{Math.round(s.completion * 100)}%</b> attempted
            </span>
            <span className="stat">
              <b>
                {solved}/{s.items.length}
              </b>{" "}
              solved
            </span>
            <span className="stat">
              overall <b>{s.overall}</b>/100
            </span>
            {s.scope.minutes ? <span className="stat">⏱ {s.scope.minutes} min</span> : null}
          </div>
        </div>
        <div className="hero-actions">
          {actionsFor(s.status).map((a) => (
            <button
              key={a.to}
              className={a.to === "abandoned" ? "hero-btn ghost" : "hero-btn"}
              onClick={() => setStatus(a.to)}
            >
              {a.label}
            </button>
          ))}
        </div>
      </section>
      {error && <div className="callout">{error}</div>}

      {s.rationale.length > 0 && (
        <ul className="rationale">
          {s.rationale.map((r) => (
            <li key={r}>{r}</li>
          ))}
        </ul>
      )}

      {s.materials.length > 0 && (
        <section>
          <h2 className="group-title">📖 Learn first</h2>
          <div className="materials">
            {s.materials.map((m) => (
              <a
                key={`${m.subject}/${m.topic}`}
                className="material"
                href={
                  m.has_lesson
                    ? `#/learn/${m.subject}/${m.topic}`
                    : `#/topic/${m.subject}/${m.topic}`
                }
              >
                <b>{m.name}</b>
                <span className="muted small">
                  {m.why ?? (m.has_lesson ? "lesson + quiz" : "topic page")}
                </span>
              </a>
            ))}
          </div>
        </section>
      )}

      <section>
        <h2 className="group-title">🧪 Problem set</h2>
        <div className="items">
          {s.items.map((it, i) => (
            <ItemRow
              key={it.id}
              item={it}
              index={i}
              onStart={(lang) => act(api.startAttempt(s.id, it.id, lang))}
            />
          ))}
        </div>
      </section>
      <p className="muted small">
        Scores come from your <code>kb run</code> results: 70 for passing cases, 20 for hitting the
        target complexity, 10 for passing on your first real try (running the empty stub doesn't
        count). Re-run an attempt and the score updates. Need a review? In Claude Code:{" "}
        <code>/review</code>.
      </p>
    </div>
  );
}

function ItemRow({
  item,
  index,
  onStart,
}: {
  item: SessionItem;
  index: number;
  onStart: (lang: "python" | "go") => void;
}) {
  const root = useContext(RootContext);
  const [copied, setCopied] = useState<string | null>(null);
  const copy = (text: string) => {
    void navigator.clipboard.writeText(text);
    setCopied(text);
    setTimeout(() => setCopied(null), 1200);
  };
  const latest = item.attempt_paths[item.attempt_paths.length - 1];
  return (
    <div className={`item ${item.state}`} style={{ ["--i" as string]: index }}>
      <div className="item-num">{index + 1}</div>
      <div className="item-main">
        <div className="item-title">
          <a href={`#/problem/${item.subject}/${item.slug}`}>{item.title ?? item.slug}</a>
          {item.difficulty && <span className={`badge ${item.difficulty}`}>{item.difficulty}</span>}
          <span className={`state ${item.state}`}>{STATE_LABEL[item.state]}</span>
        </div>
        {item.why && <div className="muted small">💡 {item.why}</div>}
        <div className="item-actions">
          {item.attempt_paths.map((p, k) => (
            <a key={p} className="attempt" href={`vscode://file${p}`} title="open in VS Code">
              ⧉ {item.attempts[k]}
            </a>
          ))}
          {latest && (
            <code
              className="cmd"
              onClick={() => copy(runCommand(latest, root))}
              title="click to copy"
            >
              {copied === runCommand(latest, root) ? "copied ✓" : runCommand(latest, root)}
            </code>
          )}
          <button onClick={() => onStart("python")}>＋ Python attempt</button>
          <button onClick={() => onStart("go")}>＋ Go attempt</button>
        </div>
      </div>
      <div className={`item-score ${scoreBand(item.score)}`}>
        {item.score === null ? "–" : item.score}
        <span>/100</span>
      </div>
    </div>
  );
}
