import { useContext, useMemo, useState } from "react";
import type { Session, SessionItem, SessionStatus } from "../api";
import { api } from "../api";
import { RootContext } from "../context";
import { designHref, problemHref } from "../route";
import {
  FOCUS_INFO,
  STATUS_LABEL,
  actionsFor,
  createdAttempt,
  isDesignItem,
  latestConsoleHref,
  runCommand,
  scoreBand,
} from "../sessions";
import { NavList } from "./panes";
import { PlanWithClaude, sessionNavGroups, useSessions } from "./PracticeBench";
import { Ring } from "./Ring";
import { Workbench, WorkbenchTab } from "./Workbench";
import { Card, Grow, InlineError, Loader, Muted, MutedP, Tinted } from "../theme/primitives";
import { t } from "../theme/theme";
import {
  ActionButton,
  Badge,
  Center,
  Empty,
  EmptyIcon,
  FooterRow,
  GroupTitle,
  ProgressFill,
  ProgressTrack,
  ScoreCard,
  ScoreChip,
  ScoreRing,
  Side,
  State,
  StatusBadge,
  StatusDot,
} from "./PracticeBench.style";
import { Row, Table, TableWrap } from "./ProblemsPage.style";
import * as S from "./SessionView.style";
import { PageHeader } from "./PageHeader";

const STATE_LABEL: Record<SessionItem["state"], string> = {
  todo: "to do",
  started: "started",
  attempted: "attempted",
  solved: "solved",
};

type SessionTab = "items" | "materials" | "results";

/** One session on the Workbench: Items / Materials / Results tabs, status actions in the footer. */
export function SessionView({ initial }: { initial: Session }) {
  const [s, setS] = useState(initial);
  const [error, setError] = useState<string | null>(null);
  const [tab, setTab] = useState<SessionTab>("items");
  const list = useSessions(undefined, s);
  const nav = useMemo(() => sessionNavGroups(list ?? [s], s.id), [list, s]);
  const act = (p: Promise<Session>) =>
    p.then(
      (next) => {
        setS(next);
        setError(null);
      },
      (e: unknown) => setError(String(e)),
    );
  const setStatus = (to: SessionStatus) => act(api.setStatus(s.id, to));
  const solved = s.items.filter((i) => i.state === "solved").length;
  const attempted = s.items.filter((i) => i.state !== "todo").length;
  const ordered = list ?? [s];
  const at = ordered.findIndex((x) => x.id === s.id);

  const header = (
    <PageHeader
      title={s.title}
      meta={[
        <StatusBadge>{STATUS_LABEL[s.status]}</StatusBadge>,
        <span>
          {FOCUS_INFO[s.target.focus].icon} {FOCUS_INFO[s.target.focus].label}
        </span>,
        s.target.goal && <span>{s.target.goal}</span>,
        <span>{Math.round(s.completion * 100)}% attempted</span>,
        <Tinted $tone="ok">
          {solved}/{s.items.length} solved
        </Tinted>,
        <span>overall {s.overall}/100</span>,
        s.scope.minutes ? <span>{s.scope.minutes} min</span> : null,
        <span>
          {s.generator === "claude" ? "planned by Claude" : "generated by kb"} ·{" "}
          {s.created.slice(0, 10)}
        </span>,
      ]}
      actions={
        <Ring
          solved={s.score ?? 0}
          total={100}
          size={44}
          label={s.score === null ? "–" : `${s.score}`}
        />
      }
    />
  );

  const tabColor: Record<SessionTab, string | undefined> = {
    items: undefined,
    materials: t.warn,
    results: t.ok,
  };
  const tabBtn = (id: SessionTab, label: string, badge: number, done = false) => (
    <WorkbenchTab
      key={id}
      on={tab === id}
      onClick={() => setTab(id)}
      color={tabColor[id]}
      badge={badge}
      done={done}
    >
      {label}
    </WorkbenchTab>
  );
  const tabs = (
    <>
      {tabBtn("items", "Items", s.items.length, solved === s.items.length && solved > 0)}
      {tabBtn("materials", "Materials", s.materials.length)}
      {tabBtn("results", "Results", attempted)}
    </>
  );

  const right = (
    <Side>
      <ScoreCard>
        <h4>Session score</h4>
        <ScoreRing>
          <Ring
            solved={s.score ?? 0}
            total={100}
            size={96}
            label={s.score === null ? "–" : `${s.score}`}
          />
        </ScoreRing>
        <ProgressTrack title={`${Math.round(s.completion * 100)}% attempted`}>
          <ProgressFill $fraction={s.completion} />
        </ProgressTrack>
        <Muted as="div" $small>
          {attempted}/{s.items.length} attempted · {solved} solved
        </Muted>
      </ScoreCard>
      {s.materials.length > 0 && (
        <Card>
          <h4>📖 Learn first</h4>
          <S.Recent>
            {s.materials.map((m) => (
              <li key={`${m.subject}/${m.topic}`}>
                <a href={materialHref(m)}>{m.name}</a>
                <Muted $small>{m.has_lesson ? "lesson" : "topic"}</Muted>
              </li>
            ))}
          </S.Recent>
        </Card>
      )}
      <PlanWithClaude />
    </Side>
  );

  const footer = (
    <FooterRow>
      <StatusBadge>{STATUS_LABEL[s.status]}</StatusBadge>
      {actionsFor(s.status).map((a) => (
        <ActionButton
          key={a.to}
          $compact
          $variant={a.to === "abandoned" ? "default" : "primary"}
          onClick={() => setStatus(a.to)}
        >
          {a.label}
        </ActionButton>
      ))}
      {error && <InlineError as="span">⚠ {error}</InlineError>}
      <Grow />
      {at >= 0 && ordered.length > 1 && (
        <Muted>
          session {at + 1} / {ordered.length}
        </Muted>
      )}
      <a href="#/sessions">all sessions →</a>
    </FooterRow>
  );

  let center;
  if (tab === "items") {
    center = (
      <>
        {s.rationale.length > 0 && (
          <S.Rationale>
            {s.rationale.map((r) => (
              <li key={r}>{r}</li>
            ))}
          </S.Rationale>
        )}
        <section>
          <GroupTitle>🧪 Problem set</GroupTitle>
          <S.Items>
            {s.items.map((it, i) => (
              <ItemRow
                key={it.id}
                item={it}
                index={i}
                onStart={(lang) => act(api.startAttempt(s.id, it.id, lang))}
                onStartDesign={() => {
                  const before = it.attempts;
                  api.startAttempt(s.id, it.id, "design").then(
                    (next) => {
                      setS(next);
                      const after = next.items.find((x) => x.id === it.id)?.attempts ?? [];
                      const created = createdAttempt(before, after);
                      if (created) window.location.hash = designHref(it.subject, it.slug, created);
                    },
                    (e: unknown) => setError(String(e)),
                  );
                }}
              />
            ))}
          </S.Items>
        </section>
      </>
    );
  } else if (tab === "materials") {
    center =
      s.materials.length === 0 ? (
        <Empty>
          <EmptyIcon>📖</EmptyIcon>
          <p>This session has no lessons to read first. Straight to the problems.</p>
        </Empty>
      ) : (
        <section>
          <GroupTitle>📖 Learn first</GroupTitle>
          <S.Materials>
            {s.materials.map((m) => (
              <S.Material key={`${m.subject}/${m.topic}`} href={materialHref(m)}>
                <b>{m.name}</b>
                <Muted $small>{m.why ?? (m.has_lesson ? "lesson + quiz" : "topic page")}</Muted>
              </S.Material>
            ))}
          </S.Materials>
        </section>
      );
  } else {
    center = (
      <S.Results>
        <GroupTitle>🏁 Results</GroupTitle>
        <TableWrap>
          <Table>
            <thead>
              <tr>
                <th>#</th>
                <th>Problem</th>
                <th>State</th>
                <th>Last run</th>
                <th>Score</th>
              </tr>
            </thead>
            <tbody>
              {s.items.map((it, i) => (
                <Row key={it.id} $status="" $i={i}>
                  <S.MutedCell>{i + 1}</S.MutedCell>
                  <td>
                    <a href={problemHref(it.subject, it.slug)}>{it.title ?? it.slug}</a>
                  </td>
                  <td>
                    <State $state={it.state}>{STATE_LABEL[it.state]}</State>
                  </td>
                  <S.MutedCell $small>
                    {it.last_run
                      ? `${it.last_run.passed}/${it.last_run.total} · ${it.last_run.ts.slice(0, 16).replace("T", " ")}`
                      : "—"}
                  </S.MutedCell>
                  <td>
                    <ScoreChip $band={scoreBand(it.score)}>
                      {it.score === null ? "–" : `${it.score}/100`}
                    </ScoreChip>
                  </td>
                </Row>
              ))}
            </tbody>
          </Table>
        </TableWrap>
        {s.history.length > 0 && (
          <>
            <h3>History</h3>
            <S.History>
              {s.history.map((h) => (
                <li key={`${h.ts}-${h.status}`}>
                  <StatusDot $status={h.status} /> {STATUS_LABEL[h.status]}
                  <Muted $small> {h.ts.slice(0, 16).replace("T", " ")}</Muted>
                </li>
              ))}
            </S.History>
          </>
        )}
        <MutedP $small>
          Scores come from your <code>kb run</code> results: 70 for passing cases, 20 for hitting
          the target complexity, 10 for passing on your first real try (running the empty stub
          doesn't count). Re-run an attempt and the score updates. Need a review? In Claude Code:{" "}
          <code>/review</code>.
        </MutedP>
      </S.Results>
    );
  }

  return (
    <Workbench
      id="sessions"
      header={header}
      tabs={tabs}
      left={{
        title: "Sessions",
        icon: "🎯",
        content: list ? (
          <NavList groups={nav} placeholder="Filter sessions…" />
        ) : (
          <Loader $small aria-label="loading" />
        ),
      }}
      right={{ title: "Score", icon: "🏁", content: right }}
      footer={footer}
    >
      <Center>{center}</Center>
    </Workbench>
  );
}

const materialHref = (m: Session["materials"][number]) =>
  m.has_lesson ? `#/learn/${m.subject}/${m.topic}` : `#/topic/${m.subject}/${m.topic}`;

function ItemRow({
  item,
  index,
  onStart,
  onStartDesign,
}: {
  item: SessionItem;
  index: number;
  onStart: (lang: "python" | "go") => void;
  onStartDesign: () => void;
}) {
  const design = isDesignItem(item);
  const consoleHref = latestConsoleHref(item);
  const root = useContext(RootContext);
  const [copied, setCopied] = useState<string | null>(null);
  const copy = (text: string) => {
    void navigator.clipboard.writeText(text);
    setCopied(text);
    setTimeout(() => setCopied(null), 1200);
  };
  const latest = item.attempt_paths[item.attempt_paths.length - 1];
  return (
    <S.Item $state={item.state} $i={index}>
      <S.ItemNum $solved={item.state === "solved"}>{index + 1}</S.ItemNum>
      <div>
        <S.ItemTitle>
          <a href={problemHref(item.subject, item.slug)}>{item.title ?? item.slug}</a>
          {item.difficulty && <Badge $difficulty={item.difficulty}>{item.difficulty}</Badge>}
          <State $state={item.state}>{STATE_LABEL[item.state]}</State>
        </S.ItemTitle>
        {item.why && (
          <Muted as="div" $small>
            💡 {item.why}
          </Muted>
        )}
        <S.ItemActions>
          {item.attempt_paths.map((p, k) => (
            <S.AttemptLink key={p} href={`vscode://file${p}`} title="open in VS Code">
              ⧉ {item.attempts[k]}
            </S.AttemptLink>
          ))}
          {latest && (
            <S.CopyCmd onClick={() => copy(runCommand(latest, root))} title="click to copy">
              {copied === runCommand(latest, root) ? "copied ✓" : runCommand(latest, root)}
            </S.CopyCmd>
          )}
          {design ? (
            <>
              {consoleHref && <a href={consoleHref}>▶ Open console</a>}
              <button onClick={onStartDesign}>＋ New design attempt</button>
            </>
          ) : (
            <>
              <button onClick={() => onStart("python")}>＋ Python attempt</button>
              <button onClick={() => onStart("go")}>＋ Go attempt</button>
            </>
          )}
        </S.ItemActions>
      </div>
      <S.ItemScore $band={scoreBand(item.score)}>
        {item.score === null ? "–" : item.score}
        <span>/100</span>
      </S.ItemScore>
    </S.Item>
  );
}
