"""Learning content: subject catalogs and lessons (validate, build traces, resolve for the studio).

Layout (subject-agnostic, so system-design can reuse it):
  <subject>/learn/catalog.json          topics (patterns / fundamentals) with aliases for problem tags
  <subject>/learn/<topic>/lesson.json   ordered blocks: markdown | trace | quiz | problems
  <subject>/learn/<topic>/traces/*.json generated by `kb learn build` (deterministic, committed)
"""

from __future__ import annotations

import json
import random
from pathlib import Path
from typing import Any

from kb import scaffold
from kb.convert import to_json, to_py
from kb.naming import SLUG_RE
from kb.paths import ROOT
from kb.schema import ProblemError, is_type, load_problem
from kb.trace import TraceError, capture, load_function, validate_view

LESSON_VERSION = 1
BLOCK_TYPES = {"markdown", "trace", "quiz", "problems"}


def learn_root() -> Path:
    return ROOT


def subjects() -> list[str]:
    return sorted(p.parent.parent.name for p in learn_root().glob("*/learn/catalog.json"))


def _check_id(value: str, what: str) -> str:
    if not SLUG_RE.match(value or ""):
        raise ProblemError(f"invalid {what}: {value!r}")
    return value


def catalog(subject: str) -> dict[str, Any]:
    path = learn_root() / _check_id(subject, "subject") / "learn" / "catalog.json"
    if not path.exists():
        raise ProblemError(f"no catalog for subject {subject!r}")
    return json.loads(path.read_text())


TOPIC_KINDS = {"pattern", "fundamental", "concept", "case-study", "principle"}
TOPIC_STATUS = {"open", "locked"}


def validate_catalog(subject: str) -> list[str]:
    """Catalog integrity: unique kebab ids, known kinds/status, prereqs/related point to real topics,
    related is symmetric, no prerequisite cycles."""
    cat, errors = catalog(subject), []
    ids = [t.get("id") for t in cat.get("topics", [])]
    if len(set(ids)) != len(ids):
        errors.append("duplicate topic ids")
    known = set(ids)
    by_id = {t["id"]: t for t in cat["topics"]}
    for t in cat["topics"]:
        where = f"{subject}/{t.get('id')}"
        if not SLUG_RE.match(str(t.get("id", ""))):
            errors.append(f"{where}: id must be kebab-case")
        if t.get("kind") not in TOPIC_KINDS:
            errors.append(f"{where}: kind must be one of {sorted(TOPIC_KINDS)}")
        if t.get("status", "open") not in TOPIC_STATUS:
            errors.append(f"{where}: status must be one of {sorted(TOPIC_STATUS)}")
        for key in ("prereqs", "related"):
            for other in t.get(key, []):
                if other not in known or other == t["id"]:
                    errors.append(f"{where}: {key} has unknown/self id {other!r}")
        for other in t.get("related", []):
            if other in by_id and t["id"] not in by_id[other].get("related", []):
                errors.append(f"{where}: related is not symmetric with {other!r}")
    state: dict[str, int] = {}

    def visit(tid: str) -> bool:  # True if a cycle is reachable
        if state.get(tid) == 1:
            return True
        if state.get(tid) == 2:
            return False
        state[tid] = 1
        cyclic = any(visit(p) for p in by_id.get(tid, {}).get("prereqs", []) if p in by_id)
        state[tid] = 2
        return cyclic

    if any(visit(tid) for tid in by_id):
        errors.append(f"{subject}: prerequisite cycle")
    return errors


def topic_ids(cat: dict[str, Any]) -> set[str]:
    return {t["id"] for t in cat["topics"]}


def alias_map(cat: dict[str, Any]) -> dict[str, str]:
    """problem pattern tag -> catalog topic id."""
    out: dict[str, str] = {}
    for t in cat["topics"]:
        out[t["id"]] = t["id"]
        for a in t.get("aliases", []):
            out[a] = t["id"]
    return out


def lesson_dir(subject: str, topic: str) -> Path:
    return learn_root() / _check_id(subject, "subject") / "learn" / _check_id(topic, "topic")


def has_lesson(subject: str, topic: str) -> bool:
    return (lesson_dir(subject, topic) / "lesson.json").exists()


def load_lesson(subject: str, topic: str) -> dict[str, Any]:
    path = lesson_dir(subject, topic) / "lesson.json"
    if not path.exists():
        raise ProblemError(f"no lesson for {subject}/{topic}")
    return json.loads(path.read_text())


def _trace_path(ldir: Path, block: dict[str, Any]) -> Path:
    return ldir / "traces" / f"{block['id']}.json"


def _typed_kwargs(block: dict[str, Any], raw: dict[str, Any]) -> dict[str, Any]:
    """JSON kwargs -> Python values using the block's optional `types` (kb meta types, e.g. ListNode)
    and `cycle` ({param: pos}: link the list's tail back to node `pos`, for cycle problems)."""
    types = block.get("types") or {}
    kwargs = {k: to_py(types[k], v) if k in types else v for k, v in raw.items()}
    for param, pos in (block.get("cycle") or {}).items():
        head, nodes = kwargs.get(param), []
        while head is not None:
            nodes.append(head)
            head = head.next
        if nodes and 0 <= pos < len(nodes):
            nodes[-1].next = nodes[pos]
    return kwargs


def _result_json(block: dict[str, Any], value: Any) -> Any:
    return to_json(block["returns"], value) if block.get("returns") else value


def build_trace(ldir: Path, block: dict[str, Any]) -> dict[str, Any]:
    fn = load_function(ldir / block["source"], block["function"])
    for i, check in enumerate(block.get("checks", [])):
        got = _result_json(block, fn(**_typed_kwargs({**block, "cycle": check.get("cycle")}, check["input"])))
        if got != check["expected"]:
            raise TraceError(f"trace {block['id']}: check {i} expected {check['expected']!r}, got {got!r}")
    return capture(
        fn,
        _typed_kwargs(block, block["input"]),
        block["view"],
        title=block.get("title", ""),
        display_input=block["input"],
        result_to_json=lambda r: _result_json(block, r),
    )


def _dump(data: Any) -> str:
    return json.dumps(data, indent=1, ensure_ascii=False, allow_nan=False) + "\n"


def build(subject: str, topic: str) -> list[Path]:
    """(Re)generate every trace of a lesson; returns written paths."""
    ldir, lesson = lesson_dir(subject, topic), load_lesson(subject, topic)
    written = []
    for block in lesson["blocks"]:
        if block.get("type") != "trace":
            continue
        path = _trace_path(ldir, block)
        path.parent.mkdir(exist_ok=True)
        content = _dump(build_trace(ldir, block))
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
        written.append(path)
    return written


def validate(subject: str, topic: str) -> list[str]:
    errors: list[str] = []
    try:
        cat = catalog(subject)
        lesson = load_lesson(subject, topic)
    except (ProblemError, json.JSONDecodeError) as e:
        return [str(e)]
    ldir, ids = lesson_dir(subject, topic), topic_ids(cat)
    if lesson.get("version") != LESSON_VERSION:
        errors.append(f"lesson.version must be {LESSON_VERSION}")
    if lesson.get("subject") != subject or lesson.get("topic") != topic:
        errors.append("lesson.subject/topic must match its directory")
    if topic not in ids:
        errors.append(f"topic {topic!r} is not in {subject}/learn/catalog.json")
    if not lesson.get("title"):
        errors.append("lesson.title is required")
    blocks = lesson.get("blocks")
    if not isinstance(blocks, list) or not blocks:
        return errors + ["lesson.blocks must be a non-empty list"]
    trace_ids: set[str] = set()
    for i, b in enumerate(blocks):
        where = f"blocks[{i}] ({b.get('type') if isinstance(b, dict) else '?'})"
        if not isinstance(b, dict) or b.get("type") not in BLOCK_TYPES:
            errors.append(f"{where}: type must be one of {sorted(BLOCK_TYPES)}")
            continue
        if b["type"] in {"markdown", "quiz"}:
            src = ldir / str(b.get("src", ""))
            if not b.get("src") or not src.is_file():
                errors.append(f"{where}: missing src file {b.get('src')!r}")
                continue
            if b["type"] == "markdown" and "<!--" in src.read_text():
                errors.append(f"{where}: {b['src']} still has <!-- --> placeholders")
            if b["type"] == "quiz":
                errors += _validate_quiz(json.loads(src.read_text()), ids, where)
        elif b["type"] == "trace":
            errors += _validate_trace_block(ldir, b, where, trace_ids)
        elif b["type"] == "problems":
            slugs = b.get("slugs")
            if not isinstance(slugs, list) or not slugs:
                errors.append(f"{where}: needs a non-empty 'slugs' list")
                continue
            for slug in slugs:
                if not (learn_root() / subject / "problems" / str(slug) / "meta.json").exists():
                    errors.append(f"{where}: unknown problem {slug!r}")
    return errors


def _validate_quiz(quiz: Any, ids: set[str], where: str) -> list[str]:
    errors: list[str] = []
    items = quiz.get("items") if isinstance(quiz, dict) else None
    if not isinstance(items, list) or not items:
        return [f"{where}: quiz needs a non-empty 'items' list"]
    seen: set[str] = set()
    for j, q in enumerate(items):
        qid = q.get("id")
        if not qid or qid in seen:
            errors.append(f"{where}: item {j} needs a unique id")
        seen.add(str(qid))
        opts = q.get("options", [])
        if not q.get("prompt") or not q.get("why"):
            errors.append(f"{where}: item {qid} needs 'prompt' and 'why'")
        if len(opts) < 2 or any(o not in ids for o in opts):
            errors.append(f"{where}: item {qid} options must be >= 2 catalog topic ids")
        if q.get("answer") not in opts:
            errors.append(f"{where}: item {qid} answer must be one of its options")
    return errors


def _validate_trace_block(ldir: Path, b: dict[str, Any], where: str, trace_ids: set[str]) -> list[str]:
    errors: list[str] = []
    tid = str(b.get("id", ""))
    if not SLUG_RE.match(tid) or tid in trace_ids:
        return [f"{where}: needs a unique kebab-case 'id'"]
    trace_ids.add(tid)
    if not (ldir / str(b.get("source", ""))).is_file() or not b.get("function"):
        return [f"{where}: needs an existing 'source' file and a 'function'"]
    if not isinstance(b.get("input"), dict):
        errors.append(f"{where}: 'input' must be an object of keyword arguments")
    for name, t in (b.get("types") or {}).items():
        if not is_type(t):
            errors.append(f"{where}: types.{name}: unknown type {t!r}")
    if b.get("returns") is not None and not is_type(b["returns"], allow_void=True):
        errors.append(f"{where}: unknown returns type {b['returns']!r}")
    errors += [f"{where}: {e}" for e in validate_view(b.get("view"))]
    if not b.get("checks"):
        errors.append(f"{where}: add 'checks' so the animated reference is verified correct")
    if errors:
        return errors
    path = _trace_path(ldir, b)
    try:
        fresh = _dump(build_trace(ldir, b))
    except Exception as e:  # noqa: BLE001 - report reference errors as validation errors
        return [f"{where}: {e}"]
    if not path.exists() or path.read_text() != fresh:
        errors.append(f"{where}: traces/{tid}.json is missing or stale — run `kb learn build`")
    return errors


# ------------------------------------------------------------------ resolve for the studio API


def resolve(subject: str, topic: str, history: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    """Lesson with block content inlined. Quiz answers are NOT included (graded server-side)."""
    ldir, lesson = lesson_dir(subject, topic), load_lesson(subject, topic)
    out_blocks = []
    for b in lesson["blocks"]:
        if b["type"] == "markdown":
            src = ldir / b["src"]
            out_blocks.append({"type": "markdown", "text": src.read_text(), "path": _repo_rel(src)})
        elif b["type"] == "trace":
            out_blocks.append({"type": "trace", "id": b["id"], "trace": json.loads(_trace_path(ldir, b).read_text())})
        elif b["type"] == "quiz":
            quiz = json.loads((ldir / b["src"]).read_text())
            items = [{"id": q["id"], "prompt": q["prompt"], "options": _shuffled(q)} for q in quiz["items"]]
            out_blocks.append({"type": "quiz", "items": items})
        elif b["type"] == "problems":
            out_blocks.append({"type": "problems", "problems": [problem_card(subject, s, history) for s in b["slugs"]]})
    names = {t["id"]: t["name"] for t in catalog(subject)["topics"]}
    return {"subject": subject, "topic": topic, "title": lesson["title"], "names": names, "blocks": out_blocks}


def _repo_rel(path: Path) -> str:
    return path.resolve().relative_to(learn_root().resolve()).as_posix()


def problem_card(subject: str, slug: str, history: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    problem = load_problem(learn_root() / subject / "problems" / _check_id(slug, "problem"))
    runs = [r for r in history or [] if r.get("slug") == slug]
    attempts = []
    for a in problem.attempts():
        last = next((r for r in reversed(runs) if r.get("attempt") == a.name), None)
        try:
            lang = scaffold.attempt_lang(a)
        except ProblemError:
            lang = "?"
        attempts.append({"name": a.name, "lang": lang, "last_run": last})
    m = problem.meta
    return {
        "slug": slug,
        "title": m["title"],
        "difficulty": m["difficulty"],
        "patterns": m["patterns"],
        "expected_complexity": m["expected_complexity"],
        "readme": (problem.dir / "README.md").read_text(),
        "readme_path": _repo_rel(problem.dir / "README.md"),
        "attempts": attempts,
    }


def _shuffled(item: dict[str, Any]) -> list[str]:
    """Deterministic per-item shuffle so the answer's position carries no signal (grading is by id)."""
    options = list(item["options"])
    random.Random(f"{item['id']}:{item['prompt']}").shuffle(options)
    return options


def grade_quiz(subject: str, topic: str, item_id: str, choice: str) -> dict[str, Any]:
    lesson = load_lesson(subject, topic)
    for b in lesson["blocks"]:
        if b["type"] != "quiz":
            continue
        quiz = json.loads((lesson_dir(subject, topic) / b["src"]).read_text())
        for q in quiz["items"]:
            if q["id"] == item_id:
                return {"correct": choice == q["answer"], "answer": q["answer"], "why": q["why"]}
    raise ProblemError(f"unknown quiz item {item_id!r}")
