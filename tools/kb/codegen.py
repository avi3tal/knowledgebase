"""Generate solution stubs (Python/Go) and the Go test harness from meta.json."""

from __future__ import annotations

import json
from string import Template
from typing import Any

from kb.naming import go_exported, snake
from kb.paths import TEMPLATES
from kb.schema import split_type, uses_structs

GO_BASE = {
    "int": "int",
    "float": "float64",
    "string": "string",
    "bool": "bool",
    "ListNode": "*ListNode",
    "TreeNode": "*TreeNode",
}
GO_ZERO = {"int": "0", "float64": "0", "string": '""', "bool": "false"}
PY_BASE = {
    "int": "int",
    "float": "float",
    "string": "str",
    "bool": "bool",
    "ListNode": "ListNode | None",
    "TreeNode": "TreeNode | None",
}


def go_type(t: str) -> str:
    base, depth = split_type(t)
    return "[]" * depth + GO_BASE[base]


def py_type(t: str) -> str:
    if t == "void":
        return "None"
    base, depth = split_type(t)
    out = PY_BASE[base]
    for _ in range(depth):
        out = f"list[{out}]"
    return out


def go_zero(t: str) -> str:
    return GO_ZERO.get(go_type(t), "nil")


def _render(path: str, **values: str) -> str:
    return Template((TEMPLATES / path).read_text()).substitute(values)


def _header(meta: dict[str, Any], attempt: str) -> dict[str, str]:
    ec = meta.get("expected_complexity", {})
    return {
        "title": meta.get("title", meta.get("slug", "")),
        "slug": meta.get("slug", ""),
        "attempt": attempt,
        "patterns": ", ".join(meta.get("patterns", [])),
        "time": ec.get("time", "?"),
        "space": ec.get("space", "?"),
    }


# ---------------------------------------------------------------- Python


def _py_params(params: list[dict[str, Any]], self_: bool = False) -> str:
    parts = ["self"] if self_ else []
    parts += [f"{p['name']}: {py_type(p['type'])}" for p in params]
    return ", ".join(parts)


def python_stub(meta: dict[str, Any], attempt: str) -> str:
    structs = sorted(uses_structs(meta))
    imports = ""
    if structs:
        imports = "from kb.structs import " + ", ".join(structs) + "\n"
    if meta["kind"] == "design":
        ctor = (meta.get("constructor") or {}).get("params", [])
        lines = [f"class {meta['class']}:", f"    def __init__({_py_params(ctor, True)}) -> None:", "        pass"]
        for m in meta["methods"]:
            body = "pass" if m["returns"] == "void" else "raise NotImplementedError"
            lines += [
                "",
                f"    def {snake(m['name'])}({_py_params(m['params'], True)}) -> {py_type(m['returns'])}:",
                f"        {body}",
            ]
        code = "\n".join(lines)
    else:
        ret = "None" if meta["returns"] == "void" else py_type(meta["returns"])
        code = f"def {snake(meta['function'])}({_py_params(meta['params'])}) -> {ret}:\n    raise NotImplementedError"
    return _render("algo/python/solution.py.tmpl", imports=imports, code=code, **_header(meta, attempt))


# ---------------------------------------------------------------- Go


def _go_params(params: list[dict[str, Any]]) -> str:
    return ", ".join(f"{p['name']} {go_type(p['type'])}" for p in params)


def _go_ret(t: str) -> str:
    return "" if t == "void" else " " + go_type(t)


def _go_body(t: str) -> str:
    return "" if t == "void" else f"\treturn {go_zero(t)}\n"


def go_stub(meta: dict[str, Any], attempt: str) -> str:
    if meta["kind"] == "design":
        cls = meta["class"]
        ctor = (meta.get("constructor") or {}).get("params", [])
        parts = [
            f"type {cls} struct{{}}\n",
            f"func New{cls}({_go_params(ctor)}) *{cls} {{\n\treturn &{cls}{{}}\n}}\n",
        ]
        for m in meta["methods"]:
            names = {p["name"] for p in m["params"]}
            recv = next(r for r in (cls[:1].lower(), cls[:2].lower(), "self", "rcv") if r not in names)
            parts.append(
                f"func ({recv} *{cls}) {go_exported(m['name'])}({_go_params(m['params'])}){_go_ret(m['returns'])} {{\n"
                f"{_go_body(m['returns'])}}}\n"
            )
        code = "\n".join(parts)
    else:
        code = (
            f"func {meta['function']}({_go_params(meta['params'])}){_go_ret(meta['returns'])} {{\n"
            f"{_go_body(meta['returns'])}}}\n"
        )
    return _render("algo/go/solution.go.tmpl", code=code.rstrip("\n"), **_header(meta, attempt))


def go_types_file(meta: dict[str, Any]) -> str | None:
    """Aliases so solutions can write *ListNode / *TreeNode like on LeetCode."""
    structs = sorted(uses_structs(meta))
    if not structs:
        return None
    aliases = "\n".join(f"type {s} = gokb.{s}" for s in structs)
    return (
        "// Code generated by kb from meta.json; DO NOT EDIT.\n\n"
        "package solution\n\n"
        'import "knowledgebase/tools/gokb"\n\n'
        f"{aliases}\n"
    )


def _decode(var: str, t: str, src: str, indent: str) -> list[str]:
    return [
        f"{indent}var {var} {go_type(t)}",
        f"{indent}if err := gokb.Decode({src}, &{var}); err != nil {{",
        f'{indent}\treturn nil, fmt.Errorf("{var}: %w", err)',
        f"{indent}}}",
    ]


def _prepare_function(meta: dict[str, Any]) -> list[str]:
    lines: list[str] = []
    for p in meta["params"]:
        lines += _decode(p["name"], p["type"], f'c.Args["{p["name"]}"]', "\t")
    call = f"{meta['function']}({', '.join(p['name'] for p in meta['params'])})"
    if meta["returns"] == "void":
        lines.append(f"\treturn func() any {{ {call}; return {meta['output']} }}, nil")
    else:
        lines.append(f"\treturn func() any {{ return {call} }}, nil")
    return lines


def _prepare_design(meta: dict[str, Any]) -> list[str]:
    cls = meta["class"]
    ctor = (meta.get("constructor") or {}).get("params", [])
    lines: list[str] = []
    for i, p in enumerate(ctor):
        lines += _decode(p["name"], p["type"], f"gokb.Arg(c.Ctor, {i})", "\t")
    lines += [
        f"\tcalls := make([]func(*{cls}) any, len(c.Ops))",
        "\tfor i, op := range c.Ops {",
        "\t\tvar args []json.RawMessage",
        "\t\tif i < len(c.OpArgs) {",
        "\t\t\targs = c.OpArgs[i]",
        "\t\t}",
        "\t\tswitch op {",
    ]
    for m in meta["methods"]:
        lines.append(f'\t\tcase "{m["name"]}":')
        for j, p in enumerate(m["params"]):
            lines += _decode(p["name"], p["type"], f"gokb.Arg(args, {j})", "\t\t\t")
        call = f"o.{go_exported(m['name'])}({', '.join(p['name'] for p in m['params'])})"
        if m["returns"] == "void":
            lines.append(f"\t\t\tcalls[i] = func(o *{cls}) any {{ {call}; return nil }}")
        else:
            lines.append(f"\t\t\tcalls[i] = func(o *{cls}) any {{ return {call} }}")
    lines += [
        "\t\tdefault:",
        '\t\t\treturn nil, fmt.Errorf("unknown op %q", op)',
        "\t\t}",
        "\t}",
        "\treturn func() any {",
        f"\t\to := New{cls}({', '.join(p['name'] for p in ctor)})",
        "\t\tout := make([]any, len(calls))",
        "\t\tfor i, call := range calls {",
        "\t\t\tout[i] = call(o)",
        "\t\t}",
        "\t\treturn out",
        "\t}, nil",
    ]
    return lines


def go_test(meta: dict[str, Any], cases_path: str = "../../cases.json") -> str:
    design = meta["kind"] == "design"
    body = _prepare_design(meta) if design else _prepare_function(meta)
    bench = "" if design else "\nfunc TestKBBench(t *testing.T) {\n\tgokb.RunBench(t, prepare)\n}\n"
    return (
        "// Code generated by kb from meta.json; DO NOT EDIT.\n"
        "// Regenerated by `kb run`; run directly with `go test .`\n\n"
        "package solution\n\n"
        "import (\n"
        '\t"encoding/json"\n'
        '\t"fmt"\n'
        '\t"testing"\n\n'
        '\t"knowledgebase/tools/gokb"\n'
        ")\n\n"
        "var (\n\t_ json.RawMessage\n\t_ = fmt.Errorf\n)\n\n"
        f"const comparator = {json.dumps(meta['comparator'])}\n\n"
        "func prepare(c gokb.Case) (gokb.Thunk, error) {\n" + "\n".join(body) + "\n}\n\n"
        "func TestCases(t *testing.T) {\n"
        f"\tgokb.RunCases(t, {json.dumps(cases_path)}, comparator"
        f", {str(design).lower()}, prepare)\n"
        "}\n" + bench
    )
